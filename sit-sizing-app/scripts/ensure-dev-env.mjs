// Creates local-only environment files with random secrets if they do not exist.
// - .env                  used by docker compose
// - apps/web/.env.local   used by `pnpm dev` on the host (database on localhost)
// Existing files are never overwritten. Nothing here is used outside a developer machine.
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const secret = () => randomBytes(18).toString('base64url');

const rootEnvPath = join(root, '.env');
if (!existsSync(rootEnvPath)) {
  const values = {
    POSTGRES_SUPERUSER_PASSWORD: secret(),
    APP_DB_PASSWORD: secret(),
    KEYCLOAK_DB_PASSWORD: secret(),
    WEB_PORT: '3000',
    DB_PORT: '5432',
    APP_ENV: 'local',
    APP_VERSION: '0.1.0-local',
    LOG_LEVEL: 'debug',
    AUTH_MODE: 'dev',
  };
  const body = Object.entries(values)
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');
  writeFileSync(
    rootEnvPath,
    `# Generated by scripts/ensure-dev-env.mjs. Local only. Do not commit.\n${body}\n`,
    {
      mode: 0o600,
    },
  );
  console.log('[sit-sizing] created .env with random local passwords');
}

const env = Object.fromEntries(
  readFileSync(rootEnvPath, 'utf8')
    .split('\n')
    .filter((l) => l && !l.startsWith('#') && l.includes('='))
    .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
);

const webEnvPath = join(root, 'apps/web/.env.local');
if (!existsSync(webEnvPath)) {
  const body = [
    'APP_ENV=local',
    'APP_VERSION=0.1.0-local',
    'LOG_LEVEL=debug',
    `DATABASE_URL=postgresql://app_user:${env.APP_DB_PASSWORD}@localhost:${env.DB_PORT ?? '5432'}/app`,
    'OTEL_SERVICE_NAME=sit-sizing-web',
    'AUTH_MODE=dev',
    '# OTEL_EXPORTER_OTLP_ENDPOINT=http://localhost:4318   # uncomment after `pnpm dev:obs`',
  ].join('\n');
  writeFileSync(
    webEnvPath,
    `# Generated by scripts/ensure-dev-env.mjs. Local only. Do not commit.\n${body}\n`,
    {
      mode: 0o600,
    },
  );
  console.log('[sit-sizing] created apps/web/.env.local for `pnpm dev` on the host');
}

// Corporate TLS inspection: containers do not see the macOS keychain, so builds fail with
// SELF_SIGNED_CERT_IN_CHAIN. Export the certificates installed in the System keychain
// (where device management puts corporate root CAs) for docker/Dockerfile to trust.
const certDir = join(root, 'docker/certs');
mkdirSync(certDir, { recursive: true });
const hasCerts = readdirSync(certDir).some((f) => /\.(pem|crt)$/i.test(f));
if (!hasCerts && process.platform === 'darwin') {
  try {
    const pem = execFileSync(
      'security',
      ['find-certificate', '-a', '-p', '/Library/Keychains/System.keychain'],
      {
        encoding: 'utf8',
        maxBuffer: 32 * 1024 * 1024,
      },
    );
    if (pem.includes('BEGIN CERTIFICATE')) {
      writeFileSync(join(certDir, 'macos-system-keychain.pem'), pem);
      console.log(
        '[sit-sizing] exported System keychain CA certificates to docker/certs/ for container builds',
      );
    }
  } catch {
    console.warn(
      '[sit-sizing] could not export keychain certificates; see docs/runbook.md "Corporate proxy"',
    );
  }
}
