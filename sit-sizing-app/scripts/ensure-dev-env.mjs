// Creates or completes local-only environment files with random secrets.
// - .env                  used by docker compose
// - apps/web/.env.local   used by `pnpm dev` on the host (database and Keycloak on localhost)
// Existing values are never changed; keys added by later steps are appended.
// Nothing here is used outside a developer machine.
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import {
  appendFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const secret = (bytes = 18) => randomBytes(bytes).toString('base64url');
const HEADER = '# Generated by scripts/ensure-dev-env.mjs. Local only. Do not commit.\n';

function readEnv(path) {
  if (!existsSync(path)) return {};
  return Object.fromEntries(
    readFileSync(path, 'utf8')
      .split('\n')
      .filter((l) => l && !l.startsWith('#') && l.includes('='))
      .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
  );
}

/** Writes the file if missing, otherwise appends only the keys it does not have yet. */
function ensureEnv(path, wanted, label) {
  const current = readEnv(path);
  const missing = Object.entries(wanted).filter(([k]) => !(k in current));
  if (!existsSync(path)) {
    writeFileSync(path, HEADER + missing.map(([k, v]) => `${k}=${v}`).join('\n') + '\n', {
      mode: 0o600,
    });
    console.log(`[sit-sizing] created ${label}`);
  } else if (missing.length) {
    appendFileSync(
      path,
      `\n# Added by a later step\n${missing.map(([k, v]) => `${k}=${v}`).join('\n')}\n`,
    );
    console.log(`[sit-sizing] added ${missing.map(([k]) => k).join(', ')} to ${label}`);
  }
  return { ...Object.fromEntries(missing), ...current };
}

const env = ensureEnv(
  join(root, '.env'),
  {
    POSTGRES_SUPERUSER_PASSWORD: secret(),
    APP_DB_PASSWORD: secret(),
    KEYCLOAK_DB_PASSWORD: secret(),
    WEB_PORT: '3000',
    DB_PORT: '5432',
    APP_ENV: 'local',
    APP_VERSION: '0.1.0-local',
    LOG_LEVEL: 'debug',
    AUTH_MODE: 'dev',
    // Step 1.3: Keycloak
    KEYCLOAK_PORT: '18080',
    KEYCLOAK_ADMIN_PASSWORD: secret(),
    OIDC_CLIENT_SECRET: secret(24),
    SESSION_SECRET: secret(32),
    // Password of the synthetic Keycloak users dev-admin, dev-lead, dev-estimator, ...
    KC_DEV_USER_PASSWORD: secret(),
  },
  '.env',
);

ensureEnv(
  join(root, 'apps/web/.env.local'),
  {
    APP_ENV: 'local',
    APP_VERSION: '0.1.0-local',
    LOG_LEVEL: 'debug',
    DATABASE_URL: `postgresql://app_user:${env.APP_DB_PASSWORD}@localhost:${env.DB_PORT ?? '5432'}/app`,
    OTEL_SERVICE_NAME: 'sit-sizing-web',
    AUTH_MODE: 'dev',
    APP_BASE_URL: 'http://localhost:3000',
    OIDC_ISSUER: `http://localhost:${env.KEYCLOAK_PORT ?? '18080'}/realms/qe-tools`,
    OIDC_CLIENT_ID: 'sit-sizing-web',
    OIDC_CLIENT_SECRET: env.OIDC_CLIENT_SECRET,
    SESSION_SECRET: env.SESSION_SECRET,
  },
  'apps/web/.env.local (for `pnpm dev` on the host)',
);

// Corporate TLS inspection: containers do not see the macOS keychain, so builds fail with
// SELF_SIGNED_CERT_IN_CHAIN. Export the certificates installed in the System keychain
// (where device management puts corporate root CAs) for docker/Dockerfile to trust.
const certDir = join(root, 'docker/certs');
mkdirSync(certDir, { recursive: true });
const hasCerts = readdirSync(certDir).some((f) => /\.(pem|crt)$/i.test(f));
if (!hasCerts && process.platform === 'darwin') {
  try {
    const pem = execFileSync(
      'security',
      ['find-certificate', '-a', '-p', '/Library/Keychains/System.keychain'],
      {
        encoding: 'utf8',
        maxBuffer: 32 * 1024 * 1024,
      },
    );
    if (pem.includes('BEGIN CERTIFICATE')) {
      writeFileSync(join(certDir, 'macos-system-keychain.pem'), pem);
      console.log(
        '[sit-sizing] exported System keychain CA certificates to docker/certs/ for container builds',
      );
    }
  } catch {
    console.warn(
      '[sit-sizing] could not export keychain certificates; see docs/runbook.md "Corporate proxy"',
    );
  }
}
